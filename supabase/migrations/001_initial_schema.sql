create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique,
  reference_code text not null unique,
  reporter_name text not null,
  reporter_nim text not null,
  reporter_email text not null,
  reporter_phone text,
  reporter_study_program text not null,
  reporter_faculty text not null,
  reported_name text not null,
  reported_nim text not null,
  reported_study_program text,
  reported_faculty text,
  category text not null references public.categories (name),
  incident_date date not null,
  incident_time text,
  incident_location text,
  description text not null,
  status text not null default 'masuk' check (status in ('masuk', 'diproses', 'selesai')),
  ai_status text not null default 'pending' check (ai_status in ('pending', 'completed', 'failed')),
  ai_analysis jsonb,
  assigned_role text check (assigned_role is null or assigned_role in (
    'Admin', 'PKKM', 'PKM', 'ASUS', 'Akademik',
    'Kemahasiswaan FTE', 'Kemahasiswaan FIF', 'Kemahasiswaan FRI',
    'Kemahasiswa FKS', 'Kemahasiswaan FKB', 'Kemahasiswaan FIK',
    'Kemahasiswaan FIT', 'Kemahasiswaan FK', 'Kemahasiswaan TUJ',
    'Kemahasiswaan TUS', 'Kemahasiswaan TUP'
  )),
  assigned_to uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists reports_created_at_idx on public.reports (created_at desc);
create index if not exists reports_status_idx on public.reports (status);
create index if not exists reports_assignee_idx on public.reports (assigned_to, assigned_role);

create table if not exists public.evidence (
  id uuid primary key default gen_random_uuid(),
  report_id uuid not null references public.reports (id) on delete cascade,
  storage_path text not null unique,
  file_name text not null,
  file_type text not null,
  file_size integer not null check (file_size > 0 and file_size <= 26214400),
  uploaded_at timestamptz not null default now()
);

create table if not exists public.follow_ups (
  id uuid primary key default gen_random_uuid(),
  report_id uuid not null references public.reports (id) on delete cascade,
  admin_id uuid not null references public.profiles (id),
  note text not null check (length(note) between 1 and 1000),
  status_new text not null check (status_new in ('masuk', 'diproses', 'selesai')),
  created_at timestamptz not null default now()
);

create index if not exists follow_ups_report_idx on public.follow_ups (report_id, created_at);

create or replace function public.add_report_follow_up(
  p_report_id uuid,
  p_admin_id uuid,
  p_status text,
  p_note text
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if p_status not in ('masuk', 'diproses', 'selesai') then
    raise exception 'Status laporan tidak valid';
  end if;
  if length(trim(p_note)) < 2 or length(p_note) > 1000 then
    raise exception 'Catatan tindak lanjut harus berisi 2-1000 karakter';
  end if;

  update public.reports
  set status = p_status, updated_at = now()
  where id = p_report_id;
  if not found then
    raise exception 'Laporan tidak ditemukan';
  end if;

  insert into public.follow_ups (report_id, admin_id, note, status_new)
  values (p_report_id, p_admin_id, trim(p_note), p_status);
end;
$$;

revoke all on function public.add_report_follow_up(uuid, uuid, text, text) from public, anon, authenticated;
grant execute on function public.add_report_follow_up(uuid, uuid, text, text) to service_role;

